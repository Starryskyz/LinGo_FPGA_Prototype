static void HostToDeviceTransfer(XScuGic *IntcController, XAxiCdma *AxiCdmaInstance,
                                 void *src_h, void *dst_d, int64_t bytelen) {
  int status = XAxiCdma_DataTransfer(IntcController, AxiCdmaInstance,
      (UINTPTR)src_h, (UINTPTR)dst_d, bytelen);
  if (status != XST_SUCCESS) abort();
}

static void DeviceToHostTransfer(XScuGic *IntcController, XAxiCdma *AxiCdmaInstance,
                                 void *src_d, void *dst_h, int64_t bytelen) {
  int status = XAxiCdma_DataTransfer(IntcController, AxiCdmaInstance,
      (UINTPTR)src_d, (UINTPTR)dst_h, bytelen);
  if (status != XST_SUCCESS) abort();
}

